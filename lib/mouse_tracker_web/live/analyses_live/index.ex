defmodule MouseTrackerWeb.AnalysesLive.Index do
  @moduledoc """
  Analyses (`/analyses`): how one or more Subjects' tracked metrics evolve
  across their chronological "done" sessions (videos), across every experiment
  each has been used in — Subject is a reusable, shared resource (see
  CLAUDE.md).

  Multiple subjects can be selected at once to overlay their trends on the
  same chart. The X axis aligns by *session index* (1st session next to 1st
  session, 2nd next to 2nd...), not by calendar date — subjects rarely share a
  timeline, but comparing "how the Nth session compares" (e.g. growth rate) is
  meaningful regardless of when each animal was actually recorded. The trend
  chart is a hand-rolled inline SVG (`LocomoComponents.trend_chart/1`) — there
  is no charting library in this app and the data here is plain Postgres
  numeric+timestamp data (unlike the heatmap/speed-profile PNGs, which are
  generated by Python from per-frame data this page doesn't have access to).
  """
  use MouseTrackerWeb, :live_view

  alias MouseTracker.Experiments

  @metrics [
    {"distance_cm", "Distance traveled", "cm"},
    {"speed_mean_cm", "Mean speed", "cm/s"},
    {"speed_median_cm", "Median speed", "cm/s"},
    {"speed_max_cm", "Max speed", "cm/s"},
    {"thigmotaxis_pct", "Thigmotaxis", "%"},
    {"path_tortuosity", "Path tortuosity", nil},
    {"immobility_seconds", "Immobility", "s"}
  ]
  @metric_keys Enum.map(@metrics, &elem(&1, 0))

  @impl true
  def mount(_params, _session, socket) do
    subjects = Experiments.list_subjects(socket.assigns.current_scope)

    {:ok,
     socket
     |> assign(:page_title, "Analyses")
     |> assign(:subjects, subjects)}
  end

  @impl true
  def handle_params(params, _uri, socket) do
    {:noreply, assign_analysis(socket, params)}
  end

  # Builds everything the page needs for the selected subjects: which
  # experiments they can be filtered to (the union across all selected
  # subjects — each may have "done" videos in several experiments, Subject is
  # reusable, see moduledoc), the chronologically-ordered sessions per
  # subject, and one trend series per subject for the selected metric.
  defp assign_analysis(socket, params) do
    subjects = socket.assigns.subjects
    selected_subjects = selected_subjects(params["subjects"], subjects)
    metric = if params["metric"] in @metric_keys, do: params["metric"], else: "distance_cm"
    scope_experiment_id = parse_int(params["scope_experiment"])
    scope = socket.assigns.current_scope

    per_subject =
      Enum.map(selected_subjects, fn subject ->
        videos = Experiments.subject_result_videos(scope, subject.id, scope_experiment_id)

        %{
          subject: subject,
          videos: videos,
          experiments: Experiments.subject_experiments(scope, subject.id),
          points: build_series(videos, metric)
        }
      end)

    socket
    |> assign(:metric, metric)
    |> assign(:scope_experiment_id, scope_experiment_id)
    |> assign(:selected_subjects, selected_subjects)
    |> assign(:all_experiments, all_experiments(per_subject))
    |> assign(:total_sessions, Enum.sum_by(per_subject, &length(&1.videos)))
    |> assign(:table_rows, table_rows(per_subject))
    |> assign(:series, series(per_subject))
  end

  defp all_experiments(per_subject) do
    per_subject
    |> Enum.flat_map(& &1.experiments)
    |> Enum.uniq_by(& &1.id)
    |> Enum.sort_by(& &1.name)
  end

  # Chronological (oldest-first) within each subject; subjects don't share a
  # timeline so grouping (not interleaving) is the only ordering that makes
  # sense here.
  defp table_rows(per_subject) do
    Enum.flat_map(per_subject, fn %{subject: s, videos: videos} ->
      videos |> Enum.reverse() |> Enum.map(&{s, &1})
    end)
  end

  defp series(per_subject) do
    per_subject
    |> Enum.map(fn %{subject: s, points: points} ->
      %{label: s.name, color: subject_color(s.id), points: points}
    end)
    |> Enum.reject(&(&1.points == []))
  end

  # `subjects` is a comma-separated list of ids in the URL (`?subjects=1,2`).
  # Absent (first visit) defaults to the first subject, same UX as before
  # multi-select existed; present-but-empty (user deselected everything) is
  # honored as "nothing selected" rather than falling back to the default.
  defp selected_subjects(nil, subjects) do
    case subjects do
      [] -> []
      [first | _] -> [first]
    end
  end

  defp selected_subjects(str, subjects) do
    valid_ids = MapSet.new(subjects, & &1.id)

    ids =
      str
      |> String.split(",", trim: true)
      |> Enum.flat_map(fn s ->
        case Integer.parse(s) do
          {id, ""} -> if MapSet.member?(valid_ids, id), do: [id], else: []
          _ -> []
        end
      end)
      |> Enum.uniq()

    Enum.filter(subjects, &(&1.id in ids))
  end

  defp unselected_subjects(subjects, selected_subjects) do
    selected_ids = MapSet.new(selected_subjects, & &1.id)
    Enum.reject(subjects, &MapSet.member?(selected_ids, &1.id))
  end

  defp parse_int(nil), do: nil

  defp parse_int(str) do
    case Integer.parse(str) do
      {id, ""} -> id
      _ -> nil
    end
  end

  # `subject_result_videos/3` orders newest-first; reverse to chronological
  # (oldest-first) for a left-to-right trend, skip videos with no tracking
  # result at all, then skip points whose specific metric is nil (some
  # metrics — thigmotaxis, tortuosity, immobility, max speed — are optional on
  # `TrackingResult` and can legitimately be missing even on a "done" video).
  defp build_series(videos, metric_key) do
    metric_atom = String.to_existing_atom(metric_key)

    videos
    |> Enum.reverse()
    |> Enum.filter(&(&1.tracking_result != nil))
    |> Enum.map(fn video ->
      %{
        video_id: video.id,
        date: video.inserted_at,
        label: Calendar.strftime(video.inserted_at, "%b %d"),
        experiment_name: video.experiment.name,
        filename: video.filename,
        value: Map.get(video.tracking_result, metric_atom)
      }
    end)
    |> Enum.reject(&is_nil(&1.value))
  end

  @impl true
  def handle_event("toggle_subject", %{"subject" => ""}, socket), do: {:noreply, socket}

  def handle_event("toggle_subject", %{"subject" => subject_id}, socket) do
    id = String.to_integer(subject_id)
    current_ids = Enum.map(socket.assigns.selected_subjects, & &1.id)

    new_ids =
      if id in current_ids, do: List.delete(current_ids, id), else: current_ids ++ [id]

    {:noreply, patch(socket, subjects: Enum.join(new_ids, ","), scope_experiment: "all")}
  end

  def handle_event("set_scope_experiment", %{"scope_experiment" => scope_experiment}, socket) do
    {:noreply, patch(socket, scope_experiment: scope_experiment)}
  end

  def handle_event("select_metric", %{"metric" => metric}, socket) do
    {:noreply, patch(socket, metric: metric)}
  end

  defp patch(socket, overrides) do
    base = [
      subjects: Enum.map_join(socket.assigns.selected_subjects, ",", &to_string(&1.id)),
      scope_experiment: socket.assigns.scope_experiment_id || "all",
      metric: socket.assigns.metric
    ]

    params =
      base
      |> Keyword.merge(overrides)
      |> Enum.reject(fn {_k, v} -> v in [nil, "all"] end)

    push_patch(socket, to: ~p"/analyses?#{params}")
  end

  @impl true
