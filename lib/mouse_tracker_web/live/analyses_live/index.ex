defmodule MouseTrackerWeb.AnalysesLive.Index do
  @moduledoc """
  Analyses (`/analyses`): how a single Subject's tracked metrics evolve across
  its chronological "done" sessions (videos), across every experiment it has
  been used in — Subject is a reusable, shared resource (see CLAUDE.md).

  One subject at a time, with a picker to switch: overlaying multiple subjects
  is the future "Compare" screen's job, not this one. The trend chart is a
  hand-rolled inline SVG (`LocomoComponents.trend_chart/1`) — there is no
  charting library in this app and the data here is plain Postgres
  numeric+timestamp data (unlike the heatmap/speed-profile PNGs, which are
  generated by Python from per-frame data this page doesn't have access to).
  """
  use MouseTrackerWeb, :live_view

  alias MouseTracker.Experiments

  @metrics [
    {"distance_cm", "Distance traveled", "cm"},
    {"speed_mean_cm", "Mean speed", "cm/s"},
    {"speed_median_cm", "Median speed", "cm/s"},
    {"speed_max_cm", "Max speed", "cm/s"},
    {"thigmotaxis_pct", "Thigmotaxis", "%"},
    {"path_tortuosity", "Path tortuosity", nil},
    {"immobility_seconds", "Immobility", "s"}
  ]
  @metric_keys Enum.map(@metrics, &elem(&1, 0))

  @impl true
  def mount(_params, _session, socket) do
    subjects = Experiments.list_subjects(socket.assigns.current_scope)

    {:ok,
     socket
     |> assign(:page_title, "Analyses")
     |> assign(:subjects, subjects)}
  end

  @impl true
  def handle_params(params, _uri, socket) do
    {:noreply, assign_analysis(socket, params)}
  end

  # Builds everything the page needs for the selected subject: which
  # experiments it can be filtered to (a subject may have "done" videos in
  # several experiments — Subject is reusable, see moduledoc), the
  # chronologically-ordered sessions, and the trend series for the selected
  # metric.
  defp assign_analysis(socket, params) do
    subjects = socket.assigns.subjects

    subject_id =
      case Integer.parse(params["subject"] || "") do
        {id, ""} -> id
        _ -> default_subject_id(subjects)
      end

    metric = if params["metric"] in @metric_keys, do: params["metric"], else: "distance_cm"

    socket =
      socket
      |> assign(:subject, Enum.find(subjects, &(&1.id == subject_id)))
      |> assign(:metric, metric)

    if socket.assigns.subject do
      scope = socket.assigns.current_scope
      scope_experiment_id = parse_int(params["scope_experiment"])

      subject_videos = Experiments.subject_result_videos(scope, subject_id, scope_experiment_id)

      socket
      |> assign(:scope_experiment_id, scope_experiment_id)
      |> assign(:subject_experiments, Experiments.subject_experiments(scope, subject_id))
      |> assign(:subject_videos, subject_videos)
      |> assign(:series, build_series(subject_videos, metric))
    else
      socket
      |> assign(:scope_experiment_id, nil)
      |> assign(:subject_experiments, [])
      |> assign(:subject_videos, [])
      |> assign(:series, [])
    end
  end

  defp default_subject_id([]), do: nil
  defp default_subject_id([%{id: id} | _]), do: id

  defp parse_int(nil), do: nil

  defp parse_int(str) do
    case Integer.parse(str) do
      {id, ""} -> id
      _ -> nil
    end
  end

  # `subject_result_videos/3` orders newest-first; reverse to chronological
  # (oldest-first) for a left-to-right trend, skip videos with no tracking
  # result at all, then skip points whose specific metric is nil (some
  # metrics — thigmotaxis, tortuosity, immobility, max speed — are optional on
  # `TrackingResult` and can legitimately be missing even on a "done" video).
  defp build_series(videos, metric_key) do
    metric_atom = String.to_existing_atom(metric_key)

    videos
    |> Enum.reverse()
    |> Enum.filter(&(&1.tracking_result != nil))
    |> Enum.map(fn video ->
      %{
        video_id: video.id,
        date: video.inserted_at,
        label: Calendar.strftime(video.inserted_at, "%b %d"),
        experiment_name: video.experiment.name,
        filename: video.filename,
        value: Map.get(video.tracking_result, metric_atom)
      }
    end)
    |> Enum.reject(&is_nil(&1.value))
  end

  @impl true
  def handle_event("select_subject", %{"subject" => subject_id}, socket) do
    {:noreply, patch(socket, subject: subject_id, scope_experiment: "all")}
  end

  def handle_event("set_scope_experiment", %{"scope_experiment" => scope_experiment}, socket) do
    {:noreply, patch(socket, scope_experiment: scope_experiment)}
  end

  def handle_event("select_metric", %{"metric" => metric}, socket) do
    {:noreply, patch(socket, metric: metric)}
  end

  defp patch(socket, overrides) do
    base = [
      subject: socket.assigns.subject && socket.assigns.subject.id,
      scope_experiment: socket.assigns.scope_experiment_id || "all",
      metric: socket.assigns.metric
    ]

    params =
      base
      |> Keyword.merge(overrides)
      |> Enum.reject(fn {_k, v} -> v in [nil, "all"] end)

    push_patch(socket, to: ~p"/analyses?#{params}")
  end

  @impl true
  def render(assigns) do
    ~H"""
    <Layouts.locomo
      flash={@flash}
      current_scope={@current_scope}
      active={:analyses}
      breadcrumb="Analyses"
      page_title="Analyses"
    >
      <div class="mx-auto max-w-[1000px]">
        <h1 class="text-[23px] font-bold text-[#0f1729]">Analyses</h1>
        <p class="mt-1 text-[13px] text-[#667085]">
          How a subject's tracked metrics change across its recording sessions over time.
        </p>

        <div
          :if={@subjects == []}
          class="mt-5 flex flex-col items-center rounded-[13px] border border-dashed border-[#d4d8df] bg-white px-6 py-16 text-center"
        >
          <div class="flex size-12 items-center justify-center rounded-full bg-[#f2f4f7] text-[#98a2b3]">
            <.icon name="hero-chart-bar" class="size-6" />
          </div>
          <h2 class="mt-4 text-[15px] font-bold text-[#0f1729]">No subjects yet</h2>
          <p class="mt-1 max-w-sm text-[13px] text-[#667085]">
            Trends appear here once you have tracked videos for at least one subject.
          </p>
        </div>

        <div :if={@subjects != []} class="mt-5">
          <div class="flex flex-wrap items-center gap-2 rounded-[13px] border border-[#e7e9ee] bg-white p-2">
            <span class="px-2 text-[11px] font-semibold uppercase tracking-wide text-[#98a2b3]">
              Subject
            </span>
            <button
              :for={s <- @subjects}
              type="button"
              phx-click="select_subject"
              phx-value-subject={s.id}
              class={[
                "inline-flex items-center gap-2 rounded-[8px] px-3 py-1.5 text-[12.5px] font-medium transition-colors",
                @subject && s.id == @subject.id && "bg-[#0f1729] text-white",
                !(@subject && s.id == @subject.id) && "text-[#667085] hover:bg-[#f2f4f7]"
              ]}
            >
              <span class="size-2 rounded-full" style={"background:#{subject_color(s.id)}"}></span>
              <span class="font-data">{s.name}</span>
            </button>
          </div>

          <div
            :if={@subject}
            class="mt-3 flex flex-wrap items-center justify-between gap-3 rounded-[13px] border border-[#e7e9ee] bg-white p-3"
          >
            <div class="text-[12.5px] text-[#667085]">
              <span class="font-data font-semibold text-[#0f1729]">{length(@subject_videos)}</span>
              analyzed session(s) for <span class="font-medium text-[#0f1729]">{@subject.name}</span>
              across
              <span class="font-data font-semibold text-[#0f1729]">{length(@subject_experiments)}</span>
              experiment(s)
            </div>
            <form id="analyses-scope-experiment" phx-change="set_scope_experiment">
              <select
                name="scope_experiment"
                class="rounded-[6px] border border-[#e7e9ee] bg-white px-2.5 py-1.5 font-data text-[12px] text-[#0f1729] focus:border-[#CC5500] focus:outline-none"
              >
                <option value="all" selected={@scope_experiment_id == nil}>All experiments</option>
                <option
                  :for={exp <- @subject_experiments}
                  value={exp.id}
                  selected={@scope_experiment_id == exp.id}
                >
                  {exp.name}
                </option>
              </select>
            </form>
          </div>

          <div
            :if={@subject && @subject_videos == []}
            class="mt-4 flex flex-col items-center rounded-[13px] border border-dashed border-[#d4d8df] bg-white px-6 py-16 text-center"
          >
            <h2 class="text-[15px] font-bold text-[#0f1729]">No analyzed sessions in this scope</h2>
            <p class="mt-1 max-w-sm text-[13px] text-[#667085]">
              Pick a different subject or widen the experiment filter.
            </p>
          </div>

          <div :if={@subject && @subject_videos != []} class="mt-4">
            <div class="inline-flex flex-wrap items-center gap-1 rounded-[9px] border border-[#e7e9ee] bg-white p-1">
              <button
                :for={{key, label, _unit} <- metrics()}
                type="button"
                phx-click="select_metric"
                phx-value-metric={key}
                class={[
                  "rounded-[6px] px-3 py-1.5 text-[12.5px] font-medium transition-colors",
                  @metric == key && "bg-[#0f1729] text-white",
                  @metric != key && "text-[#667085] hover:text-[#0f1729]"
                ]}
              >
                {label}
              </button>
            </div>

            <div class="mt-3 rounded-[13px] border border-[#e7e9ee] bg-white p-[18px] shadow-[0_1px_2px_rgba(16,24,40,.04)]">
              <div class="text-[13px] font-bold text-[#0f1729]">
                {metric_label(@metric)} over time
              </div>

              <div
                :if={@series == []}
                class="mt-6 flex flex-col items-center rounded-[10px] border border-dashed border-[#d4d8df] py-10 text-center"
              >
                <p class="text-[13px] text-[#667085]">
                  No analyzed sessions have a value for this metric yet.
                </p>
              </div>

              <div :if={@series != []} class="mt-4">
                <.trend_chart points={@series} unit={metric_unit(@metric)} />
                <p :if={length(@series) == 1} class="mt-2 text-[11.5px] text-[#8a93a3]">
                  Only one session so far — add more to see a trend.
                </p>
              </div>
            </div>

            <div class="mt-4 overflow-x-auto rounded-[13px] border border-[#e7e9ee] bg-white p-[18px] shadow-[0_1px_2px_rgba(16,24,40,.04)]">
              <table class="w-full min-w-[860px] text-left text-[12.5px]">
                <thead>
                  <tr class="border-b border-[#f4f5f7] text-[10.5px] font-semibold uppercase tracking-wide text-[#98a2b3]">
                    <th class="pb-2">Date</th>
                    <th class="pb-2">Experiment</th>
                    <th class="pb-2">Video</th>
                    <th class="pb-2">Distance</th>
                    <th class="pb-2">Mean speed</th>
                    <th class="pb-2">Thigmotaxis</th>
                    <th class="pb-2">Tortuosity</th>
                    <th class="pb-2">Immobility</th>
                  </tr>
                </thead>
                <tbody>
                  <tr
                    :for={v <- Enum.reverse(@subject_videos)}
                    class="border-b border-[#f4f5f7] last:border-0"
                  >
                    <td class="py-2.5 font-data text-[#344054]">
                      {Calendar.strftime(v.inserted_at, "%Y-%m-%d")}
                    </td>
                    <td class="py-2.5 text-[#344054]">{v.experiment.name}</td>
                    <td class="py-2.5 font-data text-[#0f1729]">{v.filename}</td>
                    <td class="py-2.5 font-data text-[#344054]">
                      {fmt(v.tracking_result && v.tracking_result.distance_cm)} cm
                    </td>
                    <td class="py-2.5 font-data text-[#344054]">
                      {fmt(v.tracking_result && v.tracking_result.speed_mean_cm)} cm/s
                    </td>
                    <td class="py-2.5 font-data text-[#344054]">
                      {fmt(v.tracking_result && v.tracking_result.thigmotaxis_pct)}%
                    </td>
                    <td class="py-2.5 font-data text-[#344054]">
                      {fmt(v.tracking_result && v.tracking_result.path_tortuosity)}
                    </td>
                    <td class="py-2.5 font-data text-[#344054]">
                      {fmt(v.tracking_result && v.tracking_result.immobility_seconds)} s
                    </td>
                  </tr>
                </tbody>
              </table>
            </div>
          </div>
        </div>
      </div>
    </Layouts.locomo>
    """
  end

  # --- helpers ---

  defp metrics, do: @metrics

  defp metric_label(key), do: metrics() |> Enum.find(&(elem(&1, 0) == key)) |> elem(1)
  defp metric_unit(key), do: metrics() |> Enum.find(&(elem(&1, 0) == key)) |> elem(2)

  defp fmt(nil), do: "—"
  defp fmt(n) when is_integer(n), do: Integer.to_string(n)
  defp fmt(n) when is_float(n), do: :erlang.float_to_binary(n, decimals: 1)
end
